describe('buildTuViChart — determinism', () => {
  it('repeated calls with identical input produce deep-equal charts (no Date.now/random/env dependency)', () => {
    const input = { birthDate: '1990-06-15', birthTime: '03:20', sex: 'Nữ' as const };
    const first = buildTuViChart(input);
    for (let i = 0; i < 10; i++) {
      expect(buildTuViChart(input)).toEqual(first);
    }
  });

  it('is frozen at every level (input, calendar, canChi, palaces, versions)', () => {
    const chart = buildTuViChart({ birthDate: '1990-06-15', birthTime: '03:20', sex: 'Nữ' });
    expect(Object.isFrozen(chart)).toBe(true);
    expect(Object.isFrozen(chart.input)).toBe(true);
    expect(Object.isFrozen(chart.calendar)).toBe(true);
    expect(Object.isFrozen(chart.canChi)).toBe(true);
    expect(Object.isFrozen(chart.palaces)).toBe(true);
    expect(Object.isFrozen(chart.versions)).toBe(true);
  });
});

describe('buildPalaceProjection', () => {
  const chart = buildTuViChart({ birthDate: '1984-02-02', birthTime: '00:30', sex: 'Nam' });
  const projection = buildPalaceProjection(chart);

  it('has exactly 12 entries, one per EarthlyBranch, in canonical order', () => {
    expect(projection).toHaveLength(12);
    expect(projection.map((e) => e.branch)).toEqual([...EARTHLY_BRANCHES]);
  });

  it('exactly one entry is marked isMenh and it matches chart.palaces.menh', () => {
    const menhEntries = projection.filter((e) => e.isMenh);
    expect(menhEntries).toHaveLength(1);
    expect(menhEntries[0]?.branch).toBe(chart.palaces.menh);
  });

  it('a dense palace (Tý, VECTOR-B1) correctly lists both its main star (Thiên Lương) and CORE_13 stars together', () => {
    const tyEntry = projection.find((e) => e.branch === 'Tý')!;
    expect(tyEntry.mainStars).toContain('Thiên Lương');
  });

  it('is a pure derived view — mutating it does not affect the underlying chart, and it is itself frozen', () => {
    expect(Object.isFrozen(projection)).toBe(true);
    expect(Object.isFrozen(projection[0])).toBe(true);
  });
});

/**
 * Invariant suite — mutation-tested. Each test constructs a shallow-mutated copy of a valid chart
 * and confirms `validateTuViChart` actually rejects that specific violation, not just that it
 * accepts valid input (a validator that never rejects anything would otherwise pass silently).
 */
describe('validateTuViChart — invariant suite (mutation-tested)', () => {
  const validChart = buildTuViChart({ birthDate: '1984-02-02', birthTime: '00:30', sex: 'Nam' });

  it('accepts a genuinely valid chart', () => {
    expect(() => validateTuViChart(validChart)).not.toThrow();
  });

  it('rejects an invalid Cục value', () => {
    const broken = { ...validChart, cuc: 'Not A Real Cục' } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/Cục/);
  });

  it('rejects a main-star array with a duplicate star ID', () => {
    const broken = { ...validChart, mainStars: [...validChart.mainStars.slice(0, -1), validChart.mainStars[0]] } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/main-star/);
  });

  it('rejects a main-star array with fewer than 14 entries', () => {
    const broken = { ...validChart, mainStars: validChart.mainStars.slice(0, 13) } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/14/);
  });

  it('rejects an auxiliary-star array with a duplicate star ID', () => {
    const broken = { ...validChart, auxiliaryStars: [...validChart.auxiliaryStars.slice(0, -1), validChart.auxiliaryStars[0]] } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/CORE_13/);
  });

  it('rejects Tuần with both palaces identical', () => {
    const broken = { ...validChart, tuan: { first: 'Tý', second: 'Tý' } } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/Tuần/);
  });

  it('rejects Triệt with both palaces identical', () => {
    const broken = { ...validChart, triet: { first: 'Sửu', second: 'Sửu' } } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/Triệt/);
  });

  it('rejects a transformations array missing one of the 4 required transformations', () => {
    const broken = { ...validChart, transformations: validChart.transformations.slice(0, 3) } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/4/);
  });

  it('rejects a palace layout with fewer than 12 roles', () => {
    const brokenLayout = { ...validChart.palaces.layout };
    delete (brokenLayout as Record<string, unknown>)['Hợi'];
    const broken = { ...validChart, palaces: { ...validChart.palaces, layout: brokenLayout } } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/12/);
  });

  it('rejects an incomplete version bundle', () => {
    const broken = { ...validChart, versions: { ...validChart.versions, engineVersion: '' } } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/version/);
  });

  it('rejects an out-of-range position value', () => {
    const broken = { ...validChart, palaces: { ...validChart.palaces, menh: 'NotABranch' } } as unknown as TuViChart;
    expect(() => validateTuViChart(broken)).toThrow(/position/);
  });
});

describe('buildTuViChart — broad invariant coverage across many real inputs', () => {
  const sampleInputs: Array<{ birthDate: string; birthTime: string; sex: 'Nam' | 'Nữ' }> = [
    { birthDate: '1990-06-15', birthTime: '03:20', sex: 'Nam' },
    { birthDate: '1990-11-25', birthTime: '14:00', sex: 'Nữ' },
    { birthDate: '2000-01-01', birthTime: '00:00', sex: 'Nam' },
    { birthDate: '2020-06-20', birthTime: '23:30', sex: 'Nữ' },
    { birthDate: '2020-06-21', birthTime: '00:30', sex: 'Nam' },
    { birthDate: '2024-02-09', birthTime: '12:00', sex: 'Nữ' },
    { birthDate: '2024-02-10', birthTime: '12:00', sex: 'Nam' },
  ];

  it.each(sampleInputs)('produces a fully valid chart for %j', (input) => {
    const chart = buildTuViChart(input);
    expect(() => validateTuViChart(chart)).not.toThrow();
  });

  it('every main star ID belongs to TU_VI_CHINH_TINH_IDS and every auxiliary star ID to TU_VI_CORE13_STAR_IDS, across all sample inputs', () => {
    for (const input of sampleInputs) {
      const chart = buildTuViChart(input);
      expect(chart.mainStars.every((s) => (TU_VI_CHINH_TINH_IDS as readonly string[]).includes(s.star))).toBe(true);
      expect(chart.auxiliaryStars.every((s) => (TU_VI_CORE13_STAR_IDS as readonly string[]).includes(s.star))).toBe(true);
    }
  });
});
