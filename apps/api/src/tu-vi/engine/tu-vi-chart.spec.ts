/**
 * RULE_DERIVED_TEST_VECTOR — VECTOR-B1 from `golden-vector-v2-spec.md` (Sprint 18A.5), run through
 * the COMPLETE composer end to end. Gregorian input (1984-02-02, 00:30) independently confirmed
 * this sprint to be Tết Giáp Tý 1984 (lunar month 1, day 1) — a well-known historical date, and the
 * same 1984=Giáp Tý anchor Eastern Horoscope's own table already uses — NOT generated by this
 * function under test; only the calendar-layer mapping (already verified in `tu-vi-calendar.adapter.spec.ts`)
 * was used to find a real Gregorian date matching B1's lunar design target.
 */
describe('buildTuViChart — VECTOR-B1 full end-to-end regression', () => {
  const chart = buildTuViChart({ birthDate: '1984-02-02', birthTime: '00:30', sex: 'Nam' });

  it('calendar layer', () => {
    expect(chart.calendar.lunarDate).toEqual({ lunarYear: 1984, lunarMonth: 1, lunarDay: 1, isLeapMonth: false });
    expect(chart.calendar.hourBranch).toBe('Tý');
  });

  it('Can Chi, Mệnh, Thân, Cục', () => {
    expect(chart.canChi.year).toEqual({ stem: 'Giáp', branch: 'Tý' });
    expect(chart.palaces.menh).toBe('Dần');
    expect(chart.palaces.than).toBe('Dần');
    expect(chart.cuc).toBe('Hỏa Lục Cục');
  });

  it('14 Chính Tinh', () => {
    const byStar = Object.fromEntries(chart.mainStars.map((p) => [p.star, p.position]));
    expect(byStar).toEqual({
      'Tử Vi': 'Dậu', 'Liêm Trinh': 'Sửu', 'Thiên Đồng': 'Thìn', 'Vũ Khúc': 'Tỵ', 'Thái Dương': 'Ngọ', 'Thiên Cơ': 'Thân',
      'Thiên Phủ': 'Mùi', 'Thái Âm': 'Thân', 'Tham Lang': 'Dậu', 'Cự Môn': 'Tuất', 'Thiên Tướng': 'Hợi', 'Thiên Lương': 'Tý', 'Thất Sát': 'Sửu', 'Phá Quân': 'Tỵ',
    });
  });

  it('CORE_13 (table-lookup and 0-offset stars)', () => {
    const byStar = Object.fromEntries(chart.auxiliaryStars.map((p) => [p.star, p.position]));
    expect(byStar['Lộc Tồn']).toBe('Dần');
    expect(byStar['Kình Dương']).toBe('Mão');
    expect(byStar['Đà La']).toBe('Sửu');
    expect(byStar['Thiên Khôi']).toBe('Sửu');
    expect(byStar['Thiên Việt']).toBe('Mùi');
    expect(byStar['Tả Phù']).toBe('Thìn');
    expect(byStar['Hữu Bật']).toBe('Tuất');
    expect(byStar['Văn Xương']).toBe('Tuất');
    expect(byStar['Văn Khúc']).toBe('Thìn');
    expect(byStar['Địa Kiếp']).toBe('Hợi');
    expect(byStar['Địa Không']).toBe('Hợi');
  });

  it('Tuần, Triệt', () => {
    expect(chart.tuan).toEqual({ first: 'Tuất', second: 'Hợi' });
    expect(chart.triet).toEqual({ first: 'Thân', second: 'Dậu' });
  });

  it('Tứ Hóa', () => {
    const byTransform = Object.fromEntries(chart.transformations.map((t) => [t.transformation, t.targetStar]));
    expect(byTransform).toEqual({ 'Hóa Lộc': 'Liêm Trinh', 'Hóa Quyền': 'Phá Quân', 'Hóa Khoa': 'Vũ Khúc', 'Hóa Kỵ': 'Thái Dương' });
  });

  it('Miếu/Vượng/Đắc/Hãm dignity is attached to every main star (spot-check against VDTTL-1956 p.33/34)', () => {
    const byStar = Object.fromEntries(chart.mainStars.map((p) => [p.star, p.dignity]));
    expect(byStar['Tử Vi']).toBe('Bình hòa'); // Dậu
    expect(byStar['Liêm Trinh']).toBe('Đắc địa'); // Sửu
  });

  it('Đại Vận starts at Mệnh with the Cục number, dương nam here so thuận', () => {
    expect(chart.daiVan[0]).toMatchObject({ ageStart: 6, ageEnd: 15, role: 'Mệnh', position: 'Dần' });
    expect(chart.daiVan[1]).toMatchObject({ ageStart: 16, ageEnd: 25, role: 'Phụ Mẫu' });
  });

  it('Tiểu Hạn start palace is deterministic for this chart\'s birth-year branch and sex', () => {
    expect(chart.tieuHanStart).toEqual({ startPalace: 'Tuất', thuan: true });
  });

  it('passes the full invariant suite', () => {
    expect(() => validateTuViChart(chart)).not.toThrow();
  });
});

